// ============================================
// MONEY FORMATTER
// ============================================


private static formatMoney(

amount:any

){


if(

amount === null ||

amount === undefined ||

amount === ""

){

return "₹0";

}




const value = Number(amount);



if(isNaN(value))

return "₹0";





return (

"₹" +

value.toLocaleString(

"en-IN"

)

);


}








